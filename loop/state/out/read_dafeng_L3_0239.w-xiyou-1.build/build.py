            if len(qs) > 1 and len({q["quote"] for q in qs}) != len(qs):
                problems.append("%s.%s 栏内重复引用" % (t["id"], f))
            for q in qs:
                if q["quote"] in seen:
                    problems.append("%s 的 %s 与 %s 共用同一句引用：%r"
                                    % (t["id"], f, seen[q["quote"]], q["quote"][:25]))

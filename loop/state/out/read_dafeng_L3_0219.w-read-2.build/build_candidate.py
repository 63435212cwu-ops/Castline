# ─────────────────────────── 自检 1：引文逐字 + 偏移 + 区间 + 哈希 ───────────────────────────
def walk_quotes(o, path=''):
    if isinstance(o, dict):
        if 'quote' in o and isinstance(o['quote'], str):
            yield path, o
        for k, v in o.items():
            yield from walk_quotes(v, path + '/' + str(k))
    elif isinstance(o, list):
        for i, v in enumerate(o):
            yield from walk_quotes(v, path + '[%d]' % i)



# ── 引用解析 ───────────────────────────────────────────────────────────────
def resolve(quote):
    pidx, sub = quote["_p"], quote["_s"]
    ptext, pabs = PARAS[pidx]
    k = ptext.find(sub)
    assert k >= 0, "子串不在该段：P%03d %r" % (pidx, sub)
    start, end = pabs + k, pabs + k + len(sub)
    assert TEXT[start:end] == sub, "偏移自检失败"
    su = 0
    for i, (a, b) in enumerate(SENT[pidx]):
        if a <= k < b:
            su = i
            break
    return {
        "quote": sub,
        "start": start,
        "end": end,
        "sourceHash": SOURCE_HASH,
        "offsetUnit": "codepoint",
        "offsetBase": "docs[0].text 全文绝对 codepoint 偏移（0-based，左闭右开）",
        "match": "exact",
        "wholeTextOccurrences": TEXT.count(sub),
        "occurrencesInRange": SLICE.count(sub),
        "paraLabel": "P%03d" % pidx,
        "sentUnit": su,
    }


def walk(node):
    if isinstance(node, dict):
        if "_p" in node and "_s" in node:
            yield node
        else:
            for v in node.values():
                yield from walk(v)
    elif isinstance(node, list):
        for v in node:
            yield from walk(v)


QUOTE_NODES = []          # 解析后的引文节点登记表（resolve 会把 _p/_s 标记消耗掉，
                          # 之后 walk() 就再也认不出它们，所以必须另存一份）


def resolve_all(root, name):
    for node in walk(root):
        resolved = resolve(node)      # 先算，再清空（顺序反了会把 _p/_s 清掉）
        node.clear()
        node.update(resolved)
        QUOTE_NODES.append((name, node))



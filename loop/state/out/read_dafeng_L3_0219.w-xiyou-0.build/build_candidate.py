def q(literal):
    """字面串 → 引文对象。

    ⚠️ 定位强度必须**写进字段**，不能靠读者假设（这是独立核验脚本抓出来的真缺陷）：
    第一版只断言「本区间内唯一」，于是分隔线 `------------`（全书出现 1031 次）也被放行，
    而它的 `start` 显然不等于 `TEXT.find(quote)`(=0)。核验脚本按更强的口径
    「find 必须等于 start」检查，立刻报 fail —— 候选没错在偏移，错在**没有声明
    这条引文不是全局唯一**。所以现在每个节点都自带：
      · wholeTextOccurrences  全书出现次数
      · inRangeOccurrences    本区间内出现次数（必须 == 1）
      · firstGlobalOffset     全书首次出现位置
      · startIsFirstGlobalOccurrence  start 是否就是首次出现
    """
    hits = [m.start() for m in re.finditer(re.escape(literal), TEXT)]
    if not hits:
        fail("引文在全书找不到：%r" % literal)
        return {"quote": literal, "start": None, "end": None, "sourceHash": SOURCE_HASH,
                "ERROR": "not-found"}
    inrange = [h for h in hits if S_START <= h and h + len(literal) <= S_END]
    if not inrange:
        fail("引文不在本区间内：%r（全书命中 %d 次：%s）" % (literal, len(hits), hits[:5]))
        return {"quote": literal, "start": None, "end": None, "sourceHash": SOURCE_HASH,
                "ERROR": "out-of-range"}
    if len(inrange) > 1:
        fail("引文在本区间内不唯一（%d 次）：%r" % (len(inrange), literal))
    start = inrange[0]
    end = start + len(literal)
    if TEXT[start:end] != literal:
        fail("回填校验失败：%r" % literal)
    return {"quote": literal, "start": start, "end": end, "sourceHash": SOURCE_HASH,
            "wholeTextOccurrences": len(hits),
            "inRangeOccurrences": len(inrange),
            "firstGlobalOffset": hits[0],
            "startIsFirstGlobalOccurrence": (hits[0] == start),
            "locatorStrength": ("globally-unique" if len(hits) == 1
                                else "unique-within-range-only（全书 %d 次，本区间仅此一次）"
                                     % len(hits))}



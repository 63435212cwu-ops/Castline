# ── 自检 1：全量引文逐字 + 偏移 + 区间 ────────────────────────────────
def walk_quotes(o, path=''):
    if isinstance(o, dict):
        if 'quote' in o and isinstance(o['quote'], str):
            yield path, o
        for k, v in o.items():
            yield from walk_quotes(v, path + '/' + str(k))
    elif isinstance(o, list):
        for i, v in enumerate(o):
            yield from walk_quotes(v, path + '[%d]' % i)

fails = []
nq = 0
for p, o in walk_quotes(cand):
    nq += 1
    q, s, e = o['quote'], o.get('start'), o.get('end')
    if not isinstance(s, int) or not isinstance(e, int):
        fails.append('缺 start/end：%s' % p); continue
    if TEXT[s:e] != q:
        fails.append('回填不符：%s' % p)
    if not (START <= s and e <= END):
        fails.append('越界：%s [%d,%d)' % (p, s, e))
    if o.get('sourceHash') != SOURCE_HASH:
        fails.append('sourceHash 不符：%s' % p)


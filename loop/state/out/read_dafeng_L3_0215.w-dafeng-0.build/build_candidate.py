with open(SRC, 'rb') as fh:
    raw = fh.read()
actual_hash = hashlib.sha256(raw).hexdigest()
assert actual_hash == SOURCE_HASH, 'sourceHash 不符：%s' % actual_hash

TEXT = json.loads(raw.decode('utf-8'))[0]['text']
SLICE = TEXT[START:END]

_cache = {}
def Q(s, basis=None):
    """定位引文；返回 {quote,start,end,sourceHash}。找不到即抛错（不许静默）。"""
    if s in _cache:
        d = dict(_cache[s])
    else:
        rel = SLICE.find(s)
        if rel < 0:
            raise SystemExit('引文不在本区间内：%r' % s)
        st = START + rel
        en = st + len(s)
        assert TEXT[st:en] == s, '回填不符：%r' % s
        assert START <= st and en <= END, '越界：%r' % s
        d = {'quote': s, 'start': st, 'end': en, 'sourceHash': SOURCE_HASH}
        _cache[s] = dict(d)
    if basis:
        d['basis'] = basis
    return d


def QL(*pairs):
    """pairs: (str) 或 (str, basis)"""
    out = []
    for p in pairs:
        if isinstance(p, tuple):
            out.append(Q(p[0], p[1]))
        else:
            out.append(Q(p))
    return out



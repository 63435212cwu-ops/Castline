def Q(s):
    """按全文 find 定位引文，取**区间内**的那一次。

    偏移口径是全文绝对偏移，但引用必须落在本单元的区间里。同一串在全书
    可能出现多次（例如排版分隔符），因此：先把所有出现位置找出来，
    **优先取落在 [START,END) 内的第一次**；区间内一次都没有才判失败。
    区间内出现多次时如实记录 inRangeOccurrences，不假装唯一。
    """
    if not isinstance(s, str) or not s:
        bad("空引文")
        return None
    idx = []
    i = TEXT.find(s)
    while i >= 0:
        idx.append(i)
        i = TEXT.find(s, i + 1)
    if not idx:
        bad("引文在全文找不到：%r" % s[:60])
        return None
    in_range_idx = [k for k in idx if k >= START and k + len(s) <= END]
    if not in_range_idx:
        bad("引文在区间 [%d,%d) 内一次都不出现：全局命中 %d 次，首次 [%d,%d) %r"
            % (START, END, len(idx), idx[0], idx[0] + len(s), s[:40]))
        return None
    st = in_range_idx[0]
    en = st + len(s)
    if TEXT[st:en] != s:
        bad("回切不一致：%r" % s[:40])
    _USED.append((st, en))
    _QUOTES.append(s)
    return {
        "quote": s,
        "start": st,
        "end": en,
        "sourceHash": DOCS_HASH,
        "wholeTextOccurrences": len(idx),
        "inRangeOccurrences": len(in_range_idx),
        "firstGlobalOffset": idx[0],
        "startIsFirstGlobalOccurrence": (st == idx[0]),
        "locatorStrength": ("globally-unique" if len(idx) == 1
                            else ("unique-in-range" if len(in_range_idx) == 1
                                  else "repeated-in-range")),
    }



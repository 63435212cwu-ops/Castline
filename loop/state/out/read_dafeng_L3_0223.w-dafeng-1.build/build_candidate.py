def _resolve(anchor, mode):
    if not isinstance(anchor, str) or not anchor:
        fail("锚串为空：%r" % (anchor,))
        return None
    occ = []
    i = TEXT.find(anchor)
    while i != -1:
        occ.append(i)
        i = TEXT.find(anchor, i + 1)
    inr = [o for o in occ if START <= o and o + len(anchor) <= END]
    if not occ:
        fail("锚串在全文 find 不到：%r" % anchor[:60])
        return None
    if not inr:
        fail("锚串只出现在区间外：%r (offsets=%r)" % (anchor[:60], occ[:5]))
        return None
    if len(inr) > 1:
        fail("锚串在本区间不唯一(%d 次)：%r" % (len(inr), anchor[:60]))
        return None
    s = inr[0]
    if mode == "e":
        e = s + len(anchor)
    elif mode == "sent":
        # 从锚串起点起，取到第一个句末标点（含紧跟的右引号）
        k = s
        while k < END and TEXT[k] not in SENT_END:
            k += 1
        if k >= END:
            fail("sent 取法越界：%r" % anchor[:60])
            return None
        e = k + 1
        if e < END and TEXT[e] == "\u201d":
            e += 1
    elif mode == "line":
        ls = TEXT.rfind("\n", START, s) + 1
        le = TEXT.find("\n", s)
        if le == -1 or le > END:
            le = END
        s, e = ls, le
        while s < e and TEXT[s] == " ":
            s += 1
        while e > s and TEXT[e - 1] == " ":
            e -= 1
    else:
        fail("未知取法 %r" % mode)
        return None
    q = TEXT[s:e]
    if TEXT[s:e] != q:
        fail("切片不等于引文：%r" % q[:40])
    if not (START <= s and e <= END):
        fail("引文越界：[%d,%d) 不在 [%d,%d)" % (s, e, START, END))
    if TEXT.find(q) == -1:
        fail("引文 find 不到：%r" % q[:40])
    RESOLVED.append((s, e, q))
    return {
        "quote": q,
        "start": s,
        "end": e,
        "sourceHash": EXPECT_SOURCE_HASH,
        "wholeTextOccurrences": len(occ),
        "inRangeOccurrences": len(inr),
        "firstGlobalOffset": occ[0],
        "startIsFirstGlobalOccurrence": (occ[0] == s),
        "locatorStrength": ("globally-unique" if len(occ) == 1
                            else ("in-range-unique" if len(inr) == 1 else "ambiguous")),
    }


def ev(anchor, mode="e"):
    r = _resolve(anchor, mode)
    return r if r else {"quote": None, "start": None, "end": None,
                        "sourceHash": EXPECT_SOURCE_HASH, "resolveError": anchor[:60]}



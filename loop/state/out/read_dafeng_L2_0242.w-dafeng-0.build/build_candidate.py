def para_of(off):
    for lab, s, e, _t in PARAS:
        if s <= off < e:
            return lab, s, e
    raise AssertionError('offset %d 不在任何段内' % off)


def q(text):
    """构造一条 quoteRef：切片内优先命中，偏移现算。"""
    if not text:
        raise AssertionError('空引文')
    occ = [m.start() for m in re.finditer(re.escape(text), TEXT)]
    if not occ:
        raise AssertionError('C1 FAIL 全文找不到：%r' % text)
    inr = [i for i in occ if i >= START and i + len(text) <= END]
    if not inr:
        raise AssertionError('C1 FAIL 命中但不在区间内：%r @ %r' % (text, occ[:5]))
    i = inr[0]
    assert TEXT[i:i + len(text)] == text, 'C1 FAIL 切片不等：%r' % text
    lab, ps, pe = para_of(i)
    return {
        'quote': text,
        'start': i,
        'end': i + len(text),
        'sourceHash': SOURCE_HASH,
        'offsetUnit': 'codepoint',
        'offsetBase': OFFSET_BASE,
        'match': 'exact',
        'wholeTextOccurrences': len(occ),
        'occurrencesInRange': len(inr),
        'paraLabel': lab,
        'contentAnchor': '%s[%d:%d]' % (lab, i - ps, i - ps + len(text)),
        'sentUnit': 0,
    }


def col(text, basis, quotes, note=None, notSuccess=False):
    d = {'text': text, 'basis': basis, 'quotes': [q(x) for x in quotes]}
    if note:
        d['note'] = note
    if notSuccess:
        d['notSuccess'] = True
    return d



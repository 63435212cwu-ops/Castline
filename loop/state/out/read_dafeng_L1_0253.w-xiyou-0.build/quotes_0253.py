_index = {}
for _name, _q in Q.items():
    hits = []
    pos = SLICE.find(_q)
    while pos >= 0:
        hits.append(pos)
        pos = SLICE.find(_q, pos + 1)
    if len(hits) == 0:
        raise SystemExit("[引文失败] %s 在本单元切片内找不到：%r" % (_name, _q[:40]))
    if len(hits) > 1:
        raise SystemExit("[引文失败] %s 在本单元切片内命中 %d 次（需唯一）：%r"
                         % (_name, len(hits), _q[:40]))
    _abs = SLICE_START + hits[0]
    assert TEXT[_abs:_abs + len(_q)] == _q, _name
    _index[_name] = {"quote": _q, "start": _abs, "end": _abs + len(_q),
                     "sourceHash": FILE_SHA256}


def q(name):
    """取一条 {quote,start,end,sourceHash}。"""
    if name not in _index:
        raise KeyError(name)
    return dict(_index[name])


def qq(*names):
    return [q(n) for n in names]



def collect(o, out):
    if isinstance(o, dict):
        if "quote" in o and "start" in o and "end" in o:
            out.append(o)
        for v in o.values():
            collect(v, out)
    elif isinstance(o, list):
        for v in o:
            collect(v, out)


def check_prose_brackets(o, where):
    """散文里的「…」必须包住逐字子串；我自己的标签一律用『…』。"""
    if isinstance(o, dict):
        for k, v in o.items():
            check_prose_brackets(v, "%s.%s" % (where, k))
    elif isinstance(o, list):
        for i, v in enumerate(o):
            check_prose_brackets(v, "%s[%d]" % (where, i))
    elif isinstance(o, str) and not (len(o) > 0 and False):
        for m in re.finditer(r"「([^」]*)」", o):
            inner = m.group(1)
            if inner and inner not in TEXT:
                PROBLEMS.append("散文「」里不是逐字原文（%s）：%r" % (where, inner[:40]))


# 每个文本字段（quote 字段本身除外）都要过这一关
def walk_texts(o, where):
    if isinstance(o, dict):
        for k, v in o.items():
            if k == "quotes":
                continue
            walk_texts(v, "%s.%s" % (where, k))
    elif isinstance(o, list):
        for i, v in enumerate(o):
            walk_texts(v, "%s[%d]" % (where, i))
    elif isinstance(o, str):
        for m in re.finditer(r"「([^」]*)」", o):
            inner = m.group(1)
            if inner and inner not in TEXT:
                PROBLEMS.append("散文「」里不是逐字原文（%s）：%r" % (where, inner[:40]))



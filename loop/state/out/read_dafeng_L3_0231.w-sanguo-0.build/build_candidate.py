def build_world_settings():
    out = []
    for w in WORLD_SETTINGS:
        rec = dict(w)
        rec["quote"] = pair(w["quote"], w["id"] + ".quote")
        if w["kind"] == "rule":
            if w.get("institution") not in ("declared", "executed", "misunderstood"):
                fail("%s kind=rule 但 institution 非法：%r" % (w["id"], w.get("institution")))
            if not w.get("explain"):
                fail("%s 缺 explain" % w["id"])
            for bad in ("placeState", "itemStates"):
                if bad in rec:
                    fail("%s kind=rule 却带 %s" % (w["id"], bad))
        elif w["kind"] == "place":
            if w.get("placeState") not in ("arrived", "mentioned"):
                fail("%s kind=place 但 placeState 非法：%r" % (w["id"], w.get("placeState")))
            if not w.get("explain"):
                fail("%s 缺 explain" % w["id"])
        elif w["kind"] == "item":
            st = w.get("itemStates")
            if not isinstance(st, list) or not st:
                fail("%s kind=item 但 itemStates 空/非列表" % w["id"])
            else:
                for s in st:
                    if s not in ("hold", "transfer", "use", "lose"):
                        fail("%s itemStates 非法值：%r" % (w["id"], s))
            if not w.get("explain"):
                fail("%s 缺 explain" % w["id"])
        else:
            fail("%s kind 非法：%r" % (w["id"], w["kind"]))
        out.append(rec)
    return out



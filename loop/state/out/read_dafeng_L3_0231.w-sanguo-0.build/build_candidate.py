def resolve_quotes(strings, where):
    out = []
    for s in strings:
        d = Q(s)
        if "_unlocated" in d:
            fail("引文定位失败 @%s：%r" % (where, s[:50]))
        out.append(d)
    return out


def pair(qdict, where):
    d = Q(qdict)
    if "_unlocated" in d:
        fail("引文定位失败 @%s：%r" % (where, qdict[:50]))
    return d


def build_tasks():
    out = []
    fieldnames = ("objective", "obstacle", "action", "result", "cost")
    for t in TASKS:
        rec = {"id": t["id"], "actor": t["actor"]}
        for f in fieldnames:
            val = t[f]
            rec[f] = val
            rec[f + "Basis"] = t[f + "Basis"]
            qs = t[f + "Quotes"]
            if val is None:
                if qs:
                    fail("%s.%s 为 null 却带引文" % (t["id"], f))
                if not t.get(f + "Note"):
                    fail("%s.%s 为 null 却没有 %sNote" % (t["id"], f, f))
            else:
                if not qs:
                    fail("%s.%s 有值却没有引文" % (t["id"], f))
                if not t.get(f + "Note"):
                    fail("%s.%s 有值却没有 %sNote" % (t["id"], f, f))
            rec[f + "Quotes"] = resolve_quotes(qs, "%s.%s" % (t["id"], f))
            rec[f + "Note"] = t.get(f + "Note")
        # 五栏引文不得共用同一句；五栏引用区间不得重叠
        seen = {}
        for f in fieldnames:
            for q in rec[f + "Quotes"]:
                s = q["quote"]
                if s in seen:
                    fail("%s 五栏共用同一句引文：%s 同时出现在 %s 与 %s"
                         % (t["id"], s[:30], seen[s], f))
                seen[s] = f
        for i, fa in enumerate(fieldnames):
            for fb in fieldnames[i + 1:]:
                for qa in rec[fa + "Quotes"]:
                    for qb in rec[fb + "Quotes"]:
                        if qa["start"] < qb["end"] and qb["start"] < qa["end"]:
                            fail("%s 的 %s 与 %s 引用区间重叠：[%d,%d) vs [%d,%d)"
                                 % (t["id"], fa, fb, qa["start"], qa["end"],
                                    qb["start"], qb["end"]))
        out.append(rec)
    return out



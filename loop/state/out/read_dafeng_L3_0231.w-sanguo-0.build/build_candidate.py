def coverage_report(all_quote_dicts):
    intervals = sorted((q["start"], q["end"]) for q in all_quote_dicts)
    merged = []
    for s, e in intervals:
        if merged and s <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], e)
        else:
            merged.append([s, e])
    union = sum(e - s for s, e in merged)
    nonspace = sum(1 for ch in QU.SLICE if not ch.isspace())
    # 段落级零覆盖
    paras = []
    off = START
    for line in QU.SLICE.split("\n"):
        if line.strip():
            paras.append((off, off + len(line), line))
        off += len(line) + 1
    zero = []
    for s, e, line in paras:
        covered = any(qs < e and s < qe for qs, qe in merged)
        if not covered:
            zero.append({"start": s, "end": e, "text": line.strip()[:60]})
    return {
        "sliceCodepoints": END - START,
        "nonSpaceCodepoints": nonspace,
        "quoteUnionCodepoints": union,
        "quoteUnionRatioOfNonSpace": round(union / nonspace, 4) if nonspace else None,
        "quoteIntervals": len(intervals),
        "mergedIntervals": len(merged),
        "paragraphs": len(paras),
        "paragraphsWithZeroCoverage": len(zero),
        "zeroCoverageParagraphs": zero,
        "note": "按「引文区间与段落区间是否有交集」计算，不是语义覆盖率。零覆盖段落多为排版分隔符、拟声词、转场符号、短对话应和与章末作者 PS；覆盖率高**不代表**语义已核验。",
    }


def collect_all_quotes(node, acc):
    if isinstance(node, dict):
        if set(node.keys()) >= {"quote", "start", "end"} and "_unlocated" not in node:
            acc.append(node)
        for v in node.values():
            collect_all_quotes(v, acc)
    elif isinstance(node, list):
        for v in node:
            collect_all_quotes(v, acc)
    return acc


def cross_task_reuse(tasks):
    where = {}
    for t in tasks:
        for f in ("objective", "obstacle", "action", "result", "cost"):
            for q in t[f + "Quotes"]:
                where.setdefault(q["quote"], []).append("%s.%s" % (t["id"], f))
    dup = {k: v for k, v in where.items() if len(v) > 1}
    return {"strings": len(dup), "detail": dup}


def cross_section_reuse(doc):
    """同一句引文在**不同分区**之间被复用的地方。

    任务明令禁止的是「同一任务的五栏共用一句」（已在 build_tasks 里强制为 0）。
    跨分区复用是**允许**的，但必须如实报数、不能声称 0 —— 否则复核者无法判断
    一处引文是不是被当成了两个不同结论的证据。

    实现：直接遍历成品的引文对象，用它的 JSON 路径的**前两段**当分区名
    （tasks 分区除外——那里的五栏碰撞由 build_tasks 单独强制）。
    """
    where = {}

    def walk(node, path):
        if isinstance(node, dict):
            if isinstance(node.get("quote"), str) and "start" in node and "end" in node:
                parts = [p for p in path.split(".") if p and not p.startswith("[")]
                section = ".".join(parts[:2]) if len(parts) >= 2 else path
                if not section.startswith("tasks"):
                    where.setdefault(node["quote"], set()).add(section)
            for k, v in node.items():
                walk(v, "%s.%s" % (path, k))
        elif isinstance(node, list):
            for i, v in enumerate(node):
                walk(v, "%s[%d]" % (path, i))

    walk(doc, "$")
    dup = {k: sorted(v) for k, v in where.items() if len(v) > 1}
    return {"strings": len(dup), "detail": dup}



def q(s):
    """构造一个引文对象：逐字、区间内、区间内唯一三条全部现算，任一为假即整脚本退出。

    **偏移必须锚在切片内**：早期版本用 TEXT.find(s) 取全文首次出现，结果
    '嘭...' 这类短句在全书先出现过 14 次、首次落在本区间之外（515091），
    算出来的 start/end 指向了别人的段落。所以这里先 SEG.find，再加 S 换算成
    全文偏移；wholeTextOccurrences 只是如实登记全文字面重复数，不参与定位。
    """
    n_seg = SEG.count(s)
    if n_seg != 1:
        PROBLEMS.append("引文在区间内出现 %d 次（要求 1）：%r" % (n_seg, s[:50]))
        return None
    start = S + SEG.find(s)
    end = start + len(s)
    if not (S <= start and end <= E):
        PROBLEMS.append("引文越界：%r" % s[:50])
        return None
    if TEXT[start:end] != s:
        PROBLEMS.append("引文不能逐字切出：%r" % s[:50])
        return None
    return {
        "quote": s,
        "start": start,
        "end": end,
        "sourceHash": SRC_HASH,
        "offsetUnit": "codepoint",
        "offsetBase": OFFSET_BASE,
        "match": "exact",
        "wholeTextOccurrences": TEXT.count(s),
        "occurrencesInRange": n_seg,
        "paraLabel": para_label(start),
        "sentUnit": sent_id(start),
    }


def qq(*ss):
    out = [q(s) for s in ss]
    return [o for o in out if o]



def T(tid, title, actor, objective, obstacle, action, result, cost, notes=None):
    """组装一条任务五元组。

    `notes` 传 dict 时，键为栏位名，写成 `<栏位>Note`（null 栏**必须**有同名 Note，
    build.py 的 C 组校验会强制）；传字符串时写入顶层 `note`。
    """
    t = {"id": tid, "title": title, "actor": actor}
    for key, col in (("objective", objective), ("obstacle", obstacle),
                     ("action", action), ("result", result), ("cost", cost)):
        if col is None:
            continue
        t[key] = col
        if col.get("note"):
            t[key + "Note"] = col.pop("note")
    if notes:
        if isinstance(notes, dict):
            for k, v in notes.items():
                if k not in ("objective", "obstacle", "action", "result", "cost"):
                    raise ValueError("notes 键必须是五栏之一，收到 %r" % k)
                t[k + "Note"] = v
        else:
            t["note"] = notes
    return t


def C(text, basis, quotes, voice="narration", note=None):
    d = {"text": text, "basis": basis, "voice": voice, "quotes": quotes}
    if note:
        d["note"] = note
    return d



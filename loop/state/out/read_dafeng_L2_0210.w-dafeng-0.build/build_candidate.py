def resolve(quote):
    pidx, sub = quote["_p"], quote["_s"]
    ptext, pabs = PARAS[pidx]
    k = ptext.find(sub)
    assert k >= 0, "子串不在该段：P%03d %r" % (pidx, sub)
    start, end = pabs + k, pabs + k + len(sub)
    assert TEXT[start:end] == sub, "偏移自检失败"
    su = 0
    for i, (a, b) in enumerate(SENT[pidx]):
        if a <= k < b:
            su = i
            break
    return {
        "quote": sub,
        "start": start,
        "end": end,
        "sourceHash": SOURCE_HASH,
        "offsetUnit": "codepoint",
        "offsetBase": "docs[0].text 全文绝对 codepoint 偏移（0-based，左闭右开）",
        "match": "exact",
        "wholeTextOccurrences": TEXT.count(sub),
        "occurrencesInRange": SLICE.count(sub),
        "paraLabel": "P%03d" % pidx,
        "sentUnit": su,
    }


def walk(node):
    if isinstance(node, dict):
        if "_p" in node and "_s" in node:
            yield node
        else:
            for v in node.values():
                yield from walk(v)
    elif isinstance(node, list):
        for v in node:
            yield from walk(v)


QUOTE_NODES = []          # resolve 会把 _p/_s 清掉，之后 walk() 认不出它们，必须另存


def resolve_all(root, name):
    for node in walk(root):
        resolved = resolve(node)      # 先算，再清空
        node.clear()
        node.update(resolved)
        QUOTE_NODES.append((name, node))


def build_per_paragraph(named_sections):
    covered = {}
    for name, node in QUOTE_NODES:
        covered.setdefault(node["paraLabel"], set()).add(name)
    rows, missing_notes = [], []
    for i in range(len(PARAS)):
        label = "P%03d" % i
        if label in covered:
            rows.append({"para": label, "state": "quoted",
                         "sections": sorted(covered[label]), "note": ""})
        else:
            note = PARA_NOTES.get(i)
            if note is None:
                missing_notes.append(label)
            rows.append({"para": label, "state": "not-quoted",
                         "sections": [], "note": note or ""})
    return rows, missing_notes



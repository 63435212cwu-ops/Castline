QUOTES = quotes.QUOTES


def q(key):
    """把一个引文键解析成带 start/end/sourceHash 的引用对象。"""
    if key not in QUOTES:
        raise KeyError("未登记的引文键：%s" % key)
    return dict(QUOTES[key])


def slot(text, basis, keys, note=None):
    d = {"text": text, "basis": basis, "quotes": [q(k) for k in keys]}
    if note:
        d["note"] = note
    return d


def ref(key):
    return q(key)



# ── 句单元：**先按段（非空行）切，再在段内切句**。───────────────
# 为什么不能对整片直接切（本脚本第一版就是这个 bug，被五栏判据抓出来）：
# 中文引语的收尾引号 ” 在句末标点**之后**，直接对全片切会让边界落在 ” 之前，
# 于是下一句的单元里混进上一句的尾引号 —— 表现为『求求你了』与『一口拒绝』被判成同一单元，

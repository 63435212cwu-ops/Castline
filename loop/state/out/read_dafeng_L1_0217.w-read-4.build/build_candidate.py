def para_covered(a, b):
    """半开区间重叠判据：a < y 且 x < b。

    本脚本第一版这里是错的（写成 `not (b <= x or a <= y)`，即把
    `x >= b or y <= a` 当成了「不重叠」）—— 于是**被整段引用的段**反而被判成零覆盖，
    把 2 个其实被覆盖的段报成零覆盖。这正是复核者最容易抓的假数字，
    所以判据本身要有对拍：见下面 COVERAGE 自检（整段引用的段必须判为已覆盖）。
    """
    return any(a < y and x < b for x, y in ALL_QUOTE_RANGES)



def split_units(para_start, para_text):
    out = []
    p = 0
    for m in UNIT_RE.finditer(para_text):
        e = m.end()
        while e < len(para_text) and para_text[e] in CLOSERS:
            e += 1
        if e > p:
            out.append((para_start + p, para_start + e))
        p = e
    if p < len(para_text):
        out.append((para_start + p, para_start + len(para_text)))
    return out



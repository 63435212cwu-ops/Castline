def q(s):
    """在切片里定位一条引文，返回带全文偏移的对象。找不到/不唯一/越界 ⇒ 记录失败。"""
    i = SEG.find(s)
    if i < 0:
        bad("引文在切片内找不到：%r" % s[:70])
        return {"quote": s, "start": None, "end": None, "sourceHash": SOURCE_HASH, "_BAD": True}
    if SEG.find(s, i + 1) >= 0:
        bad("引文在切片内不唯一：%r" % s[:70])
    a, b = S + i, S + i + len(s)
    if not (S <= a < b <= E):
        bad("引文越界：[%d,%d)" % (a, b))
    if text[a:b] != s:
        bad("text[start:end] != quote：%r" % s[:70])
    doc_count = text.count(s)
    first_doc = text.find(s)
    obj = {
        "quote": s,
        "start": a,
        "end": b,
        "docOccurrences": doc_count,
        "sliceOccurrences": 1,
        "sourceHash": SOURCE_HASH,
    }
    if first_doc != a:
        obj["offsetNote"] = ("该串在全文中首次出现于 %d，不在本区间；本候选给的 start=%d 是**落在本单元切片内**"
                             "的那一次出现（SEG.find 所得），并已断言 text[start:end]==quote。" % (first_doc, a))
    return obj


def field(text_, basis, quotes, note=None):
    d = {"text": text_, "basis": basis, "quotes": quotes}
    if note:
        d["note"] = note
    return d



# ── 引号规范化（机器可复算）──────────────────────────────────────────────
# 源文本只使用 “ ”（`『』「」` 在全书出现 0 次、`…` 在本切片出现 0 次）。
# 因此候选散文里凡是想**逐字引用原文**的地方一律用源文本自己的 “ ”；
# 凡是我自己的术语/转述一律去掉引号（不给原文安它没有的字符）。
import re as _re


def normalize_prose_str(x):
    if not isinstance(x, str):
        return x

    def _sub(m):
        inner = m.group(1)
        if len(inner) >= 4 and inner in TEXT:
            return "\u201c" + inner + "\u201d"
        return inner

    x = _re.sub(r"\u300c([^\u300c\u300d]*)\u300d", _sub, x)
    x = _re.sub(r"\u300e([^\u300e\u300f]*)\u300f", _sub, x)
    return x


def normalize_prose(node):
    if isinstance(node, dict):
        return {k: normalize_prose(v) for k, v in node.items()}
    if isinstance(node, list):
        return [normalize_prose(v) for v in node]
    return normalize_prose_str(node)



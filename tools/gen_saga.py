def expand_char(t, idx):
    """把一条 CHARS 元组展开成完整角色对象（确定性，无随机）。"""
    name, role, importance, camp, stance, brief, traits = t
    affs = ROLE_AFF.get(role, (0,) * len(DIMS))
    attrs = {}
    for di, dim in enumerate(DIMS):
        wobble = ((idx * 7 + di * 13) % 21) - 10
        score = max(20, min(99, importance + affs[di] + wobble))
        low = score < 35
        pool = EV[dim]
        text = pool[3] if low else pool[idx % 3]
        attrs[dim] = {
            "score": score,
            "evidence": [text.format(name=name, camp=camp)],
            "basis": SOURCES[camp] + "·" + ERAS[idx % len(ERAS)],
            "low": low,
        }
    return {
        "name": name,
        "role": role,
        "importance": importance,
        "camp": camp,
        "stance": stance,
        "identity": camp + "·" + role,
        "brief": brief,
        "traits": list(traits),
        "attrs": attrs,
    }



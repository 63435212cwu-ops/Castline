# ---------------------------------------------------------------- 原文装载
def load_corpus():
    """按固定顺序读入四份原文，返回 (拼接全文, 按文件名索引的文本)。"""
    names = ("角色设定.md", "第0卷 第一卷 星落.md", "第1卷 第二卷 迷航.md", "第2卷 第三卷 归港.md")
    texts = {}
    for name in names:
        path = os.path.join(SRC_DIR, name)
        with open(path, encoding="utf-8") as fh:
            texts[name] = unicodedata.normalize("NFC", fh.read())
    return "\n".join(texts.values()), texts


# ---------------------------------------------------------------- 策展数据
def attr(score, evidence, basis, low=None):
    e = list(evidence)
    if low is None:
        low = not e
    return {"score": score, "evidence": e, "basis": basis, "low": low}



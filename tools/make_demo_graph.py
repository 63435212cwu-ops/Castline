    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验现存文件，不重写")
    args = ap.parse_args()

    corpus, _ = load_corpus()
    specs = {
        "demo.json": build_graph("星尘信使", DEMO_CAST, DEMO_EVENTS, DEMO_RELATIONS,
                                 DEMO_SYNOPSIS, {"model": "demo", "analyzed_at": "2026-10-16"}),
        "dryrun.json": build_graph("星尘信使·演练", DRYRUN_CAST, dryrun_events(),
                                   [{k: r[k] for k in ("a", "b", "kind", "strength", "desc")} for r in DEMO_RELATIONS],
                                   DRYRUN_SYNOPSIS, {"model": "demo-dryrun", "analyzed_at": "2026-10-16"}),
    }
    ok = True
    for name, spec in specs.items():
        ok &= validate(spec, corpus)
    if not ok:
        return 1
    if args.check:
        for name, spec in specs.items():
            with open(os.path.join(OUT_DIR, name), encoding="utf-8") as fh:
                cur = json.load(fh)
            ok &= check(cur == spec, "现存文件与内置规格一致", name)
        return 0 if ok else 1
    for name, spec in specs.items():
        with open(os.path.join(OUT_DIR, name), "w", encoding="utf-8") as fh:
            json.dump(spec, fh, ensure_ascii=False, indent=1)
            fh.write("\n")
        print("写出", os.path.join(OUT_DIR, name),
              "(%d 角色 / %d 事件 / %d 关系)" % (len(spec["characters"]), len(spec["events"]), len(spec["relations"])))
    return 0



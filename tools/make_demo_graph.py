def build_graph(title, cast, events, relations, synopsis, meta):
    """按章节号升序落 order，并补上chapter标签；出场名单收窄到本图的角色表
    （演练图含岑媪，示例图不含——同一剧情流在两图里的可见集合不同）。"""
    cast_names = {c["name"] for c in cast}
    evs = []
    for i, (num, ch_name, etitle, summary, chars, kind, quote) in enumerate(events, 1):
        evs.append({"chapter": "第%d章 %s" % (num, ch_name), "title": etitle, "summary": summary,
                    "characters": [n for n in chars if n in cast_names], "kind": kind, "quote": quote, "order": i})
    return {"title": title, "synopsis": synopsis, "characters": cast, "events": evs,
            "relations": relations, "meta": meta}



# ---------------------------------------------------------------- 校验
def check(cond, msg, detail=""):
    if not cond:
        print("FAIL: %s %s" % (msg, detail))
        return False
    return True


def validate(graph, corpus):
    ok = True
    cast_names = {c["name"] for c in graph["characters"]}
    ok &= check(len(cast_names) == len(graph["characters"]), "角色名唯一")
    for c in graph["characters"]:
        ok &= check(c["role"] in C_ROLES, "role 合法", c["name"])
        ok &= check(0 <= c["importance"] <= 100, "importance 在 0-100", c["name"])
        ok &= check(set(c["attrs"]) == set(DIMS), "八维齐全", c["name"])
        for dim, a in c["attrs"].items():
            ok &= check((a["evidence"] and not a["low"]) or (not a["evidence"] and a["low"]),
                        "evidence 为空则 low", "%s·%s" % (c["name"], dim))
            for e in a["evidence"]:
                ok &= check(e in corpus, "证据为原文逐字子串", "%s·%s: %s" % (c["name"], dim, e[:24]))
        for j in c["judgments"]:
            ok &= check(j["kind"] in E_KINDS, "judgment kind 合法", c["name"])
    orders = [e["order"] for e in graph["events"]]
    ok &= check(orders == list(range(1, len(orders) + 1)), "order 连续从 1 开始")
    for e in graph["events"]:
        ok &= check(e["kind"] in E_KINDS, "事件 kind 合法", e["title"])
        ok &= check(e["quote"] in corpus, "引句为原文逐字子串", e["title"] + ": " + e["quote"][:24])
        ok &= check(set(e["characters"]) <= cast_names, "事件角色均在角色表", e["title"])
    for r in graph["relations"]:
        ok &= check({r["a"], r["b"]} <= cast_names, "关系端点均在角色表", r["a"] + "-" + r["b"])
        ok &= check(0 < r["strength"] <= 1, "关系强度在 (0,1]", r["a"] + "-" + r["b"])
    return ok



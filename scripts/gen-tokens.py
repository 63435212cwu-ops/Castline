#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Castline · 色板 → CSS token 生成器（gen_tokens · 零依赖 · 不启浏览器）

星渊宪法 G1：js/palette.js 是全项目唯一的语义色真相。
本脚本从 palette.js 提取事件色 / 阵营色 / 语义色 / 深渊灰阶，
生成 css/app-shell.css 头部的「受保护区」:root 变量块 —— CSS 侧不再手写色值。

A1 消化口径（2026-10-04 信息层清零）：受保护区自 app.css 迁至 app-shell.css，
块内字面值改挂 oklch 等值 —— 命中 css/abyss-tokens.css 既有 8-bit 同值令牌的
引 var(--abyss-*)（拒绝回指向本生成块的链，防止 --sem-* ↔ --abyss-* 循环断链），
无对应令牌者由 palette hex 现场换算 oklch(L% C H)，逐条做 8-bit 往返零误差自检。
tmp 判例：oklch_to_rgb8(rgb8_to_oklch 格式化串) == 原 hex 逐字节相等。

用法：
  python3 -s scripts/gen-tokens.py            # 校验 app-shell.css 受保护区与 palette.js 一致
  python3 -s scripts/gen-tokens.py --write    # 用最新生成块覆盖 app-shell.css 受保护区
  python3 -s scripts/gen-tokens.py --stdout   # 只打印生成块，不碰文件

退出码：0 一致 / 1 不一致或失败
"""
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PALETTE_JS = os.path.join(ROOT, 'js', 'palette.js')
SHELL_CSS = os.path.join(ROOT, 'css', 'app-shell.css')
ABYSS_TOKENS_CSS = os.path.join(ROOT, 'css', 'abyss-tokens.css')

GUARD_OPEN = '/* === ABYSS TOKENS · generated by scripts/gen-tokens.py — DO NOT EDIT === */'
GUARD_CLOSE = '/* === end ABYSS TOKENS === */'

DIGEST_NOTE = (
    '/* A1 消化注记（2026-10-04 信息层清零）：本块色值字面改挂 oklch 等值——逐条往返\n'
    '   8-bit 零误差校验（值域未动，语义与 palette.js 单一真相不变；css_lint 裸色冻结令\n'
    '   对生成块一视同仁，此处不再手写 hex/rgba 字面）。 */'
)

EMIT_PREFIXES = ('--evt-', '--camp-', '--sem-', '--grey-')
EMIT_NAMES = {
    '--bg', '--ink', '--ink-2', '--ink-3', '--signal', '--signal-2',
    '--violet', '--violet-2', '--mint', '--cyan', '--hot',
}


# ---------------------------------------------------------------- sRGB ↔ Oklch
def _srgb_to_linear(c):
    c = c / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def _linear_to_srgb(c):
    return 12.92 * c if c <= 0.0031308 else 1.055 * (c ** (1.0 / 2.4)) - 0.055


def rgb8_to_oklch(r, g, b):
    rl, gl, bl = _srgb_to_linear(r), _srgb_to_linear(g), _srgb_to_linear(b)
    l = 0.4122214708 * rl + 0.5363325363 * gl + 0.0514459929 * bl
    m = 0.2119034982 * rl + 0.6806995451 * gl + 0.1073969566 * bl
    s = 0.0883024619 * rl + 0.2817188376 * gl + 0.6299787005 * bl
    l_, m_, s_ = l ** (1.0 / 3.0), m ** (1.0 / 3.0), s ** (1.0 / 3.0)
    L = 0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_
    A = 1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_
    B = 0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_
    return L, math.hypot(A, B), math.degrees(math.atan2(B, A)) % 360.0


def oklch_to_rgb8(L, C, H):
    hr = math.radians(H)
    a, b = C * math.cos(hr), C * math.sin(hr)
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_ ** 3, m_ ** 3, s_ ** 3
    rl = +4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    gl = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s

    def q(x):
        return int(math.floor(max(0.0, min(255.0, _linear_to_srgb(x) * 255.0)) + 0.5))

    return q(rl), q(gl), q(bl)


def _trim(x, ndigits):
    s = '%.*f' % (ndigits, x)
    return s.rstrip('0').rstrip('.') if '.' in s else s


def fmt_oklch(r, g, b):
    """hex 三通道 → oklch 字面（L%.2f · C%.4f · H%.1f 去尾零），8-bit 往返零误差自检；
    自检不过自动升精度重修，仍不过即拒绝生成（宁红不漂移）。"""
    L, C, H = rgb8_to_oklch(r, g, b)
    for ld, cd, hd in ((2, 4, 1), (3, 5, 2), (4, 6, 3)):
        s = 'oklch(%s%% %s %s)' % (_trim(round(L * 100, ld), ld), _trim(round(C, cd), cd), _trim(round(H, hd), hd))
        m = re.fullmatch(r'oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)', s)
        if oklch_to_rgb8(float(m.group(1)) / 100.0, float(m.group(2)), float(m.group(3))) == (r, g, b):
            return s
    raise SystemExit('FAIL · #%02x%02x%02x 无法用 oklch 等值零误差表达' % (r, g, b))


# ---------------------------------------------------------------- palette.js 解析
def hex6(v):
    if isinstance(v, int):
        return format(v, '06x')
    return ('000000' + format(int(v, 16), '06x'))[-6:]


def hex_rgb(v):
    h = hex6(v.lstrip('#') if isinstance(v, str) and v.startswith('#') else v)
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def parse_js_arrays(src):
    """从 palette.js 源码里正则提取顶层数组 / 对象字面量（ES5，无嵌套花括号陷阱）。"""
    out = {}

    def grab(name, pattern, cast):
        m = re.search(r'var\s+' + name + r'\s*=\s*' + pattern, src, re.S)
        if not m:
            raise SystemExit('FAIL · palette.js 找不到 var %s' % name)
        out[name] = cast(m.group(1))

    def arr(s):
        return re.findall(r"'([^']*)'|0x([0-9a-fA-F]{6})|#([0-9a-fA-F]{6})", s)

    def arr_hex(s):
        return [int(h, 16) for _, h, _ in arr(s)]

    def obj_int(s):
        d = {}
        for k, h in re.findall(r"([A-Za-z0-9_]+):\s*0x([0-9a-fA-F]{6})", s):
            d[k] = int(h, 16)
        return d

    grab('CSS', r'\[([^\]]*)\]', arr)
    grab('CAMP_CSS', r'\[([^\]]*)\]', lambda s: re.findall(r"'([^']*)'", s))
    grab('CAMP_HEX', r'\[([^\]]*)\]', arr_hex)
    grab('SEM', r'\{\s*([^}]*)\}', obj_int)
    grab('GREY', r'\{\s*([^}]*)\}', obj_int)
    return out


# ------------------------------------------------------- abyss-tokens 同值令牌图
_CORE_RANK = ['--abyss-mint', '--abyss-mint-bright', '--abyss-signal', '--abyss-signal-bright',
              '--abyss-violet', '--abyss-violet-bright', '--abyss-gold']


def _abyss_rank(name):
    if name in _CORE_RANK:
        return (0, _CORE_RANK.index(name))
    if name.startswith('--abyss-camp-'):
        return (1, name)
    if name.startswith('--abyss-lad-'):
        return (2, name)
    return (3, name)


def load_abyss_color_map():
    """解析 css/abyss-tokens.css :root，产出 (r,g,b) → 首选令牌名。

    只收不透明色（alpha=1）；能解 rgb(var(--abyss-rgb-*)) 元组与 abyss 内部 var 链；
    凡链上触及本生成块签发名（--sem-*/--grey-*/--bg/--hot 等）的一律拒收——
    否则 --sem-violetLo 若引 --abyss-violet-dim 就会和它互指成环双双失效。"""
    txt = open(ABYSS_TOKENS_CSS, encoding='utf-8').read()
    txt = re.sub(r'/\*.*?\*/', lambda m: re.sub(r'[^\n]', ' ', m.group(0)), txt, flags=re.S)
    m = re.search(r':root\s*\{', txt)
    if not m:
        raise SystemExit('FAIL · abyss-tokens.css 找不到 :root 块')
    i, depth = m.end(), 1
    while depth > 0:
        if txt[i] == '{':
            depth += 1
        elif txt[i] == '}':
            depth -= 1
        i += 1
    decls = {}
    for vm in re.finditer(r'(--[A-Za-z0-9_-]+)\s*:\s*([^;}]+)', txt[m.end():i - 1]):
        decls[vm.group(1)] = vm.group(2).strip()

    def hits_emit(name, seen, d):
        if name in EMIT_NAMES or name.startswith(EMIT_PREFIXES):
            return True
        if d > 14 or name in seen:
            return True
        raw = decls.get(name)
        if raw is None:
            return True
        ref = re.search(r'var\(\s*(--[A-Za-z0-9_-]+)', raw)
        return bool(ref and hits_emit(ref.group(1), seen | {name}, d + 1))

    def resolve(name, seen, d):
        """→ (r,g,b) 或 None（非不透明色 / 链触签发名 / 解不出）。"""
        if d > 14 or name in seen:
            return None
        raw = decls.get(name)
        if raw is None:
            return None
        seen = seen | {name}
        hex_m = re.fullmatch(r'#([0-9a-fA-F]{6})', raw)
        if hex_m:
            h = hex_m.group(1)
            return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
        tup_m = re.fullmatch(r'rgb\(\s*var\(\s*(--abyss-rgb-[a-z-]+)\s*\)\s*\)', raw)
        if tup_m:
            tup = decls.get(tup_m.group(1), '')
            parts = re.fullmatch(r'\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*', tup)
            return (int(parts.group(1)), int(parts.group(2)), int(parts.group(3))) if parts else None
        ref = re.fullmatch(r'var\(\s*(--abyss-[a-z0-9-]+)\s*\)', raw)
        if ref and not hits_emit(ref.group(1), seen, d):
            return resolve(ref.group(1), seen, d + 1)
        return None

    by_val = {}
    for name in decls:
        if name in EMIT_NAMES or name.startswith(EMIT_PREFIXES):
            continue
        if hits_emit(name, set(), 0):
            continue
        c = resolve(name, set(), 0)
        if c is None:
            continue
        if c not in by_val or _abyss_rank(name) < _abyss_rank(by_val[c]):
            by_val[c] = name
    return by_val


# ---------------------------------------------------------------- 生成块
def gen_block(css_list, camp_css_list, sem, grey, abyss_map):
    """每条色板值：命中 abyss 同值令牌 → var(--abyss-*)；否则现场换算 oklch 字面。"""
    def ref(v):
        name = abyss_map.get(v)
        return 'var(%s);' % name if name else fmt_oklch(*v) + ';'

    lines = [GUARD_OPEN, DIGEST_NOTE]
    lines.append(':root{')
    kinds = ['高燃', '转折', '抉择', '冲突', '关系', '领悟', '日常']
    for i, c in enumerate(css_list):
        lines.append('  --evt-%d:%s' % (i, ref(hex_rgb(c))))
    lines.append('  /* 事件色命名映射（语义 → 序号） */')
    for i, k in enumerate(kinds):
        lines.append('  --evt-%s:var(--evt-%d);' % (k, i))
    camps = ['主角方', '盟友', '中立', '摇摆', '对立']
    for i, c in enumerate(camp_css_list[:-1]):
        lines.append('  --camp-%d:%s' % (i, ref(hex_rgb(c))))
    for i, k in enumerate(camps):
        lines.append('  --camp-%s:var(--camp-%d);' % (k, i))
    lines.append('  --camp-散星:%s' % ref(hex_rgb(camp_css_list[-1])))
    for k, v in sem.items():
        lines.append('  --sem-%s:%s' % (k, ref(hex_rgb(v))))
    for k, v in grey.items():
        lines.append('  --grey-%s:%s' % (k, ref(hex_rgb(v))))
    lines.append('  /* 兼容别名（旧代码直接引用，禁止再手写色值） */')
    lines.append('  --bg:var(--grey-bg);')
    lines.append('  --ink:var(--grey-ink);')
    lines.append('  --ink-2:var(--grey-s5);')
    lines.append('  --ink-3:var(--grey-s4);')
    lines.append('  --signal:var(--sem-signal);')
    lines.append('  --signal-2:var(--sem-signalHi);')
    lines.append('  --violet:var(--sem-violet);')
    lines.append('  --violet-2:var(--sem-violetLo);')
    lines.append('  --mint:var(--sem-mint);')
    lines.append('  --cyan:var(--sem-signal);')
    lines.append('  --hot:var(--sem-hot);')
    lines.append('}')
    lines.append(GUARD_CLOSE)
    return '\n'.join(lines) + '\n'


def extract_guard(css):
    m = re.search(re.escape(GUARD_OPEN) + r'.*?' + re.escape(GUARD_CLOSE), css, re.S)
    return m.group(0) if m else None


def main():
    write = '--write' in sys.argv
    stdout = '--stdout' in sys.argv
    src = open(PALETTE_JS, encoding='utf-8').read()
    d = parse_js_arrays(src)
    m_css = re.search(r'var\s+CSS\s*=\s*\[([^\]]*)\]', src)
    css_list = re.findall(r"'([^']*)'", m_css.group(1))
    block = gen_block(css_list, d['CAMP_CSS'], d['SEM'], d['GREY'], load_abyss_color_map())

    if stdout:
        sys.stdout.write(block)
        return 0

    css = open(SHELL_CSS, encoding='utf-8').read()
    old = extract_guard(css)
    if old is None:
        print('FAIL · app-shell.css 没有受保护区（%s）' % GUARD_OPEN)
        return 1
    if old == block.rstrip('\n'):
        print('OK · app-shell.css 受保护区与 palette.js 一致')
        return 0
    if not write:
        print('MISMATCH · app-shell.css 受保护区与 palette.js 不一致（用 --write 更新）')
        return 1
    open(SHELL_CSS, 'w', encoding='utf-8').write(css.replace(old, block.rstrip('\n')))
    print('WROTE · app-shell.css 受保护区已更新')
    return 0


if __name__ == '__main__':
    sys.exit(main())
